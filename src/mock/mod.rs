/// Mock Engine — Autonomous HTTP Mock Server & Stubs Generator.
///
/// Converts synthesized API contracts (`ApiRoute`s / `architecture.md`) into:
///  1. An embedded, zero-dependency async HTTP mock server running on Tokio
///  2. A standalone Bun/TypeScript mock server (`replica/mock-server.ts`)
///
/// Allows frontend interfaces, tests, and client SDKs to be developed and verified
/// immediately on day 1 without waiting for database provisioning or backend code.
use crate::types::ApiRoute;
use anyhow::{Context, Result};
use std::fs;
use std::path::Path;
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::TcpListener;

pub struct MockEngine;

impl MockEngine {
    /// Export a standalone Bun/TypeScript mock server file
    pub fn export_bun_mock_server<P: AsRef<Path>>(
        routes: &[ApiRoute],
        out_path: P,
        port: u16,
    ) -> Result<()> {
        let mut ts = String::new();
        ts.push_str("// Auto-generated by replica-square mock — DO NOT EDIT MANUALLY\n");
        ts.push_str("// Autonomous Mock Server powered by Bun / Hono\n\n");
        ts.push_str(&format!("const PORT = {};\n\n", port));
        ts.push_str("const routes = [\n");

        for r in routes {
            let output_sample = if r.output_schema.trim().starts_with('{') {
                r.output_schema.trim()
            } else {
                "{\"status\": \"ok\", \"data\": []}"
            };

            ts.push_str(&format!(
                "  {{ method: \"{}\", path: \"{}\", response: {} }},\n",
                r.method.to_uppercase(),
                r.path,
                output_sample
            ));
        }

        ts.push_str("];\n\n");
        ts.push_str(r#"
console.log(`🚀 [Replica Mock Server] Listening on http://localhost:${PORT}`);

Bun.serve({
  port: PORT,
  fetch(req) {
    const url = new URL(req.url);
    const method = req.method.toUpperCase();

    // Enable universal CORS
    if (method === "OPTIONS") {
      return new Response(null, {
        headers: {
          "Access-Control-Allow-Origin": "*",
          "Access-Control-Allow-Methods": "GET, POST, PUT, DELETE, PATCH, OPTIONS",
          "Access-Control-Allow-Headers": "Content-Type, Authorization, x-api-key",
        },
      });
    }

    const matched = routes.find(r => r.method === method && url.pathname.startsWith(r.path));
    if (matched) {
      console.log(`[MOCK] ${method} ${url.pathname} -> 200 OK`);
      return new Response(JSON.stringify(matched.response), {
        headers: {
          "Content-Type": "application/json",
          "Access-Control-Allow-Origin": "*",
        },
      });
    }

    console.log(`[MOCK] ${method} ${url.pathname} -> 404 Not Found`);
    return new Response(JSON.stringify({ error: "Route not found in replica API contract", path: url.pathname }), {
      status: 404,
      headers: { "Content-Type": "application/json", "Access-Control-Allow-Origin": "*" },
    });
  },
});
"#);

        fs::write(out_path.as_ref(), ts)
            .with_context(|| format!("Writing mock server to {:?}", out_path.as_ref()))?;

        Ok(())
    }

    /// Run an embedded zero-dependency HTTP mock server in Tokio
    pub async fn run_embedded_server(routes: Vec<ApiRoute>, port: u16) -> Result<()> {
        let addr = format!("127.0.0.1:{}", port);
        let listener = TcpListener::bind(&addr)
            .await
            .with_context(|| format!("Binding mock server to {}", addr))?;

        println!("🚀 [Replica Mock Server] Live at http://{}", addr);
        println!("   Loaded {} mock endpoint contract(s)", routes.len());

        loop {
            let (mut socket, peer) = listener.accept().await?;
            let routes_clone = routes.clone();

            tokio::spawn(async move {
                let mut buf = [0u8; 4096];
                let n = match socket.read(&mut buf).await {
                    Ok(n) if n > 0 => n,
                    _ => return,
                };

                let req_str = String::from_utf8_lossy(&buf[..n]);
                let first_line = req_str.lines().next().unwrap_or("");
                let parts: Vec<&str> = first_line.split_whitespace().collect();

                let method = parts.first().copied().unwrap_or("GET");
                let full_path = parts.get(1).copied().unwrap_or("/");
                let path = full_path.split('?').next().unwrap_or("/");

                if method == "OPTIONS" {
                    let resp = "HTTP/1.1 204 No Content\r\n\
                        Access-Control-Allow-Origin: *\r\n\
                        Access-Control-Allow-Methods: GET, POST, PUT, DELETE, OPTIONS\r\n\
                        Access-Control-Allow-Headers: Content-Type, Authorization\r\n\
                        Connection: close\r\n\r\n";
                    let _ = socket.write_all(resp.as_bytes()).await;
                    return;
                }

                let matched = routes_clone.iter().find(|r| {
                    r.method.eq_ignore_ascii_case(method) && path.starts_with(&r.path)
                });

                let (status, body) = if let Some(r) = matched {
                    let b = if r.output_schema.trim().starts_with('{') {
                        r.output_schema.trim()
                    } else {
                        "{\"status\":\"ok\",\"replica_mock\":true}"
                    };
                    ("200 OK", b.to_string())
                } else {
                    ("404 Not Found", format!("{{\"error\":\"Endpoint not found\",\"path\":\"{}\"}}", path))
                };

                println!("   [{}] {} {} -> {}", peer, method, path, status);

                let http_response = format!(
                    "HTTP/1.1 {}\r\n\
                    Content-Type: application/json\r\n\
                    Content-Length: {}\r\n\
                    Access-Control-Allow-Origin: *\r\n\
                    Connection: close\r\n\r\n{}",
                    status,
                    body.len(),
                    body
                );

                let _ = socket.write_all(http_response.as_bytes()).await;
            });
        }
    }
}
